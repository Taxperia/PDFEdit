// Collect installed production package notices without adding a build dependency.
import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const lock = JSON.parse(await readFile(path.join(root, 'package-lock.json'), 'utf8'))
const notices = ['PDFEdit - third-party runtime license notices\n\nGenerated by npm run licenses. Font licensing is in fonts/OFL.txt.\n']

for (const [location, metadata] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b))) {
  // Optional native canvas packages are Node-only and are not shipped by Vite.
  if (!location || metadata.dev || metadata.optional) continue
  const directory = path.join(root, location)
  let pkg
  try { pkg = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8')) }
  catch (error) { if (error.code === 'ENOENT' && metadata.optional) continue; throw error }
  const names = (await readdir(directory)).filter((name) => /^(licen[sc]e|copying|notice)(\.|$)/i.test(name)).sort()
  if (!names.length) {
    // This package ships its notices alongside the UMD build instead of at root.
    if (pkg.name === '@pdf-lib/fontkit') names.push('README.md', 'dist/fontkit.umd.js')
    else throw new Error(`Missing license notice for ${pkg.name}`)
  }
  notices.push(`\n${'='.repeat(72)}\n${pkg.name} ${pkg.version}\nLicense: ${pkg.license ?? metadata.license ?? 'See notice'}\n`)
  for (const name of names) {
    let text = await readFile(path.join(directory, name), 'utf8')
    if (name.endsWith('.js')) {
      text = [...text.matchAll(/\/\*[\s\S]*?\*\//g)].map(([comment]) => comment).filter((comment) => /copyright|licen[sc]e|permission/i.test(comment)).join('\n\n')
      if (!text) throw new Error(`Missing embedded notices for ${pkg.name}`)
    }
    notices.push(`\n--- ${name} ---\n${text.trim()}\n`)
  }
}
const normalizedNotices = notices.join('').replaceAll('\r\n', '\n').replace(/[ \t]+$/gm, '')
await writeFile(path.join(root, 'public', 'THIRD_PARTY_LICENSES.txt'), normalizedNotices, 'utf8')
await writeFile(path.join(root, 'public', 'LICENSE.txt'), await readFile(path.join(root, 'LICENSE'), 'utf8'), 'utf8')
console.log('Updated public/THIRD_PARTY_LICENSES.txt')
